from collections import deque

"""Heuristic 1: O(n) - Number of unsorted rows

---
"""

def heuristic_1(state):
    n = state.shape[0]  # Grid size
    count = 0
    for row in state:
        if not np.all(row == np.sort(row)):  # Check if the row is sorted
            count += 1
    return count

"""Heuristic 2: O(n^2) - Total Manhattan distance

---


"""

def heuristic_2(state):
    n = state.shape[0]  # Grid size
    total_distance = 0
    for value in range(1, n * n + 1):  # Loop through all values in the grid
        current_position = np.argwhere(state == value)[0]  # Find current position
        target_position = np.array([(value - 1) // n, (value - 1) % n])  # Calculate target position
        total_distance += np.abs(current_position - target_position).sum()  # Add Manhattan distance
    return total_distance

"""Generate all possible moves by shifting rows and columns

---


"""

def generate_moves(state):
    n = state.shape[0]  # Grid size
    moves = []
    # Shift rows
    for row in range(n):
        for shift in range(1, n):  # Shift by 1 to n-1 positions
            new_state = np.copy(state)
            new_state[row] = np.roll(new_state[row], shift)  # Cyclic shift
            moves.append(new_state)
    # Shift columns
    for col in range(n):
        for shift in range(1, n):  # Shift by 1 to n-1 positions
            new_state = np.copy(state)
            new_state[:, col] = np.roll(new_state[:, col], shift)  # Cyclic shift
            moves.append(new_state)
    return moves

"""Solve using BFS with Heuristics

---


"""

def bfs_with_heuristics(initial_state, heuristic_function):
    n = initial_state.shape[0]  # Grid size
    goal_state = np.arange(1, n * n + 1).reshape(n, n)  # Goal state (sorted grid)

    # Priority queue for BFS (state, depth, heuristic value)
    queue = deque([(initial_state, 0, heuristic_function(initial_state))])
    visited = set()  # Keep track of visited states

    while queue:
        # Sort queue by heuristic value (smallest depth + heuristic first)
        queue = deque(sorted(queue, key=lambda x: x[1] + x[2]))

        # Get the state with the smallest depth + heuristic
        current_state, depth, _ = queue.popleft()
        if not np.array_equal(current_state, initial_state):
            print(f"Perform move -> \n{current_state}")

        state_tuple = tuple(map(tuple, current_state))  # Convert state to a hashable format

        # Check if goal is reached
        if np.array_equal(current_state, goal_state):
            print(f"Final state -> \n{current_state}")
            return depth  # Return the minimum number of moves

        # Skip already visited states
        if state_tuple in visited:
            continue
        visited.add(state_tuple)  # Mark current state as visited

        # Generate and process all possible moves
        for move in generate_moves(current_state):
            move_tuple = tuple(map(tuple, move))
            if move_tuple not in visited:
                heuristic_value = heuristic_function(move)
                queue.append((move, depth + 1, heuristic_value))  # Add to queue with updated depth

    return -1  # Return -1 if no solution is found (should not happen for this problem)

