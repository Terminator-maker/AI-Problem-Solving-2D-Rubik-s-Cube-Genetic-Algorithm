TARGET_Y = 1  # Target value for y
X = np.array([4, -2, 3.5, 5])  # Input coefficients
POPULATION_SIZE = 50  # Adjusted population size
GENERATIONS = 100  # Increased number of generations
INITIAL_MUTATION_RATE = 0.15  # Adjustable mutation rate
MUTATION_DECAY = 0.95  # Gradually reduce mutation rate
BOUNDS = [-10, 10]  # Bounds for weights (w values)

"""Initialize the population with random values

---


"""

def initialize_population(size, dimensions):
    return np.random.uniform(BOUNDS[0], BOUNDS[1], (size, dimensions))

"""Error calculation using absolute difference instead of squared error

---


"""

def fitness_function(weights):
    y = np.dot(weights, X)
    return abs(TARGET_Y - y)  # Absolute error

"""Selection: Weighted selection based on inverse error

---


"""

def select_parents(population, fitness):
    fitness_adjusted = 1 / (fitness + 1e-6)
    probabilities = fitness_adjusted / fitness_adjusted.sum()
    parent_indices = np.random.choice(len(population), size=2, p=probabilities)
    return population[parent_indices[0]], population[parent_indices[1]]

"""Crossover: Single-point crossover with a twist

---


"""

def crossover(parent1, parent2):
    point = np.random.randint(0, len(parent1))  # Allow crossover at index 0
    child1 = np.concatenate((parent1[:point], parent2[point:]))
    child2 = np.concatenate((parent2[:point], parent1[point:]))
    return child1, child2

"""Mutation: Apply multiple mutations with dynamic probability

---


"""

def mutate(individual, mutation_rate):
    for i in range(len(individual)):
        if np.random.rand() < mutation_rate:
            individual[i] += np.random.uniform(-0.5, 0.5)  # Random change in the weight
            individual[i] = np.clip(individual[i], BOUNDS[0], BOUNDS[1])  # Clip to stay within bounds
    return individual

"""Genetic Algorithm Execution

---


"""

def genetic_algorithm():
    population = initialize_population(POPULATION_SIZE, len(X))
    mutation_rate = INITIAL_MUTATION_RATE
    for generation in range(GENERATIONS):
        # Evaluate calculated y for the population
        calculated_y = np.array([np.dot(ind, X) for ind in population])

        # Filter out individuals with y > 1
        valid_indices = np.where(calculated_y <= 1)[0]
        population = population[valid_indices]

        # Calculate fitness for the filtered population
        fitness = np.array([fitness_function(ind) for ind in population])

        fitness = np.array([fitness_function(ind) for ind in population])
        new_population = []
        while len(new_population) < POPULATION_SIZE:
            # Select parents
            parent1, parent2 = select_parents(population, fitness)
            # Crossover to produce offspring
            child1, child2 = crossover(parent1, parent2)
            # Apply mutations
            child1 = mutate(child1, mutation_rate)
            child2 = mutate(child2, mutation_rate)
            new_population.extend([child1, child2])
        population = np.array(new_population[:POPULATION_SIZE])
        mutation_rate *= MUTATION_DECAY  # Reduce mutation rate over time

    # Find and return the best solution
    fitness = np.array([fitness_function(ind) for ind in population])
    best_index = np.argmin(fitness)
    return population[best_index], np.dot(population[best_index], X)

"""Run the Genetic Algorithm And Store The First 100 Results

---


"""

results = []
for i in range(100):
    optimal_weights, calculated_y = genetic_algorithm()
    results.append((optimal_weights, calculated_y))

